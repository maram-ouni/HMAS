# ─────────────────────────────────────────────────────────
# strategy_learner.py -- AUTONOMOUS STRATEGY LEARNING
#
# Design : multi-armed bandit without predefined categories
#
# Principle :
#   Agent PE freely explores the strategy space.
#   No categories imposed by the developer.
#   Only the payoff guides learning :
#     payoff >= KEEP_THRESHOLD -> EXPLOITATION (reuse)
#     payoff <  KEEP_THRESHOLD -> EXPLORATION  (LLM generates new plan)
#
# The LLM sees what failed and invents a different approach.
# Strategies emerge from experience, not from a fixed list.
#
# GT Link :
#   PE explores sigma in an infinite (unconstrained) space.
#   It converges toward sigma* = argmax_sigma U_PE(sigma).
#   This is a true strategy optimization problem.
#
# ─────────────────────────────────────────────────────────

import json
import math
import os
import sys
import threading
import time
from dataclasses import dataclass, field
from typing import List, Optional

from openai import OpenAI

sys.path.insert(0, os.path.dirname(os.path.dirname(os.path.abspath(__file__))))
from config import GROQ_API_KEY, GROQ_BASE_URL, LLM_MODEL, RESULTS_DIR
from core.payoff_calculator import PE_SUCCESS_THRESHOLD

# PE keeps a strategy only if U_PE >= PE_SUCCESS_THRESHOLD (0.7)
# Below that : the strategy is acceptable (partial) but PE continues to explore
KEEP_THRESHOLD = PE_SUCCESS_THRESHOLD


@dataclass
class ActionStrategy:
    """
    A strategy = a text plan + its payoff U_PE.

    No predefined category -- the strategy is a
    free-form description generated by the LLM.
    The payoff is the sole selection criterion.
    """
    steps:      List[str]   # plan generated by the LLM
    payoff:     float       # U_PE obtained
    reward:     float       # 0.0 or 1.0
    task_type:  str
    run_number: int
    steps_used: int
    timestamp:  float = field(default_factory=time.time)
    # Which PlanLibrary plan produced `steps[0]` (the recorded hint), if
    # any — "" for records written before this field existed, or for
    # hints not tied to a named plan. Used as the UCB1 arm key: unlike
    # the raw hint text (e.g. Fallback's hint embeds attempt count and
    # best_u_v, so it is never byte-identical twice), plan_name gives a
    # stable, small set of arms with meaningful per-arm sample sizes.
    plan_name:  str = ""


class StrategyLearner:
    """
    Autonomous strategy learning driven by payoff signal.

    No predefined categories.
    The LLM freely generates new strategies
    by observing what failed and inventing something different.

    Learning cycle :
      1. First run     : LLM generates an initial plan
      2. Good payoff   : EXPLOITATION -- reuse the same plan
      3. Bad payoff    : EXPLORATION  -- LLM generates a different plan
                         based on past failures
      4. Convergence   : the plan with the best payoff dominates
    """

    def __init__(self, results_dir: str = None, keep_threshold: float = None):
        self.client          = OpenAI(api_key=GROQ_API_KEY, base_url=GROQ_BASE_URL)
        # Isolated-memory override (None = today's hardcoded RESULTS_DIR,
        # shared across runs — see config.MEMORY_DIR).
        self._results_dir     = results_dir or RESULTS_DIR
        self.strategies_file = os.path.join(self._results_dir, "learned_strategies.json")
        self.strategies: dict = {}
        self._lock = threading.Lock()
        # Per-instance override of the module-level KEEP_THRESHOLD (opt-in
        # — see config.LEARNED_PE_WEIGHTS / core/verifier_learned_weights
        # .calibrate_threshold). None (default) preserves today's behavior
        # exactly.
        self.keep_threshold = keep_threshold if keep_threshold is not None else KEEP_THRESHOLD
        self._load_from_disk()

    # ── Before the run : choose or generate ──────────────────

    def _generate_freely(self,
                          task_goal:        str,
                          failed_histories: list,
                          tried_descriptions: list) -> List[str]:
        """
        Generates a plan freely, without predefined categories.

        The LLM sees :
          - The task to accomplish
          - What failed in past runs (if available)
          - What has already been tried this session (to avoid)

        It produces a plan in natural language.
        """
        failed_section = ""
        if failed_histories:
            lines = []
            for s in failed_histories[-4:]:
                steps_preview = " -> ".join(s.steps[:3])
                lines.append(
                    f"  Failure (U_PE={s.payoff:.3f}, steps={s.steps_used}) : "
                    f"{steps_preview}"
                )
            failed_section = (
                "\nPAST STRATEGIES THAT FAILED (to avoid) :\n"
                + "\n".join(lines) + "\n"
            )

        tried_section = ""
        if tried_descriptions:
            tried_section = (
                "\nALREADY TRIED THIS SESSION (do not reproduce) :\n"
                + "\n".join(f"  - {d}" for d in tried_descriptions[:3])
                + "\n"
            )

        prompt = f"""You are a web agent navigating AN ALREADY OPEN WEB PAGE.

TASK : {task_goal}

IMPORTANT CONTEXT :
- You are ALREADY on the web page, no need to search the internet
- At each step you will see the AXTree (list of page elements with their bids)
- Bids are numbers like '649', '55', etc. — you will find them in the AXTree
- You navigate the site directly (like a user clicking)

{failed_section}{tried_section}
AVAILABLE ACTIONS :
  scroll(0, 400)          -> scroll the page to see more elements
  click("bid")            -> click on an element visible in the AXTree
  fill("bid", "text")     -> type text into a search field
  press("Enter")          -> submit a search
  send_msg_to_user("rep") -> send the final answer (ENDS the task)

NAVIGATION LOGIC (like DemoAgent) :
1. First check if the answer is ALREADY VISIBLE in the AXTree
   -> if yes : send_msg_to_user('value') immediately (1 single step)
2. Otherwise, navigate with minimum clicks :
   - Find the target element in the list/page (its bid will be visible)
   - Click on it to access the detail
   - Read the value and send it

RULES :
- Maximum 5 steps
- NO external or internet search — we are on the page
- DO NOT invent bids — they will be found in the AXTree at execution time
- Last step : send_msg_to_user("exact value found")

Respond ONLY in JSON :
{{
  "steps": [
    "Check if the answer is visible in the current AXTree",
    "If not visible : identify and click the element leading to the information",
    "Read the value in the new page",
    "send_msg_to_user('exact value')"
  ]
}}"""

        try:
            resp = self.client.chat.completions.create(
                model    = LLM_MODEL,
                messages = [{"role": "user", "content": prompt}],
                max_tokens  = 400,
                temperature = 0.4,
            )
            text = resp.choices[0].message.content.strip()
            if "```" in text:
                for part in text.split("```"):
                    if part.startswith("json"):
                        text = part[4:].strip(); break
                    elif "{" in part:
                        text = part.strip(); break
            data  = json.loads(text)
            steps = data.get("steps", [])
            if steps:
                return steps
        except Exception as e:
            print(f"  [Learner] Generation failed : {e}")

        # Minimal fallback
        return [
            "look at the current AXTree to find the requested information",
            "if visible : send_msg_to_user('exact value')",
            "otherwise : scroll(0, 400) and search again",
        ]

    # ── After the run : record the payoff ────────────────────

    def record_run(self,
                   task_type:  str,
                   steps:      List[str],
                   payoff:     float,
                   reward:     float,
                   steps_used: int,
                   run_number: int,
                   plan_name:  str = "",
                   ) -> None:
        """
        Records the result of a run.
        The payoff determines whether this plan will be reused.
        No category -- the plan is identified by its steps.
        """
        strategy = ActionStrategy(
            steps      = steps,
            payoff     = payoff,
            reward     = reward,
            task_type  = task_type,
            run_number = run_number,
            steps_used = steps_used,
            plan_name  = plan_name,
        )
        with self._lock:
            if task_type not in self.strategies:
                self.strategies[task_type] = []
            self.strategies[task_type].append(strategy)
        self._save_to_disk()

        status   = "OK  " if reward >= 1.0 else "FAIL"
        decision = "KEEP" if payoff >= self.keep_threshold else "CHANGE"
        print(f"\n  [Learner] [{status}] U_PE={payoff:.3f} -> {decision}")

    # ── Access ────────────────────────────────────────────────

    def get_strategies_for_task(self, task_type: str) -> List[ActionStrategy]:
        return self.strategies.get(task_type, [])

    def get_best_strategy(self, task_type: str) -> Optional[ActionStrategy]:
        strats = self.strategies.get(task_type, [])
        return max(strats, key=lambda s: s.payoff) if strats else None

    def get_best_hint(self, task_type: str,
                      exclude: Optional[List[str]] = None,
                      require_success: bool = True) -> str:
        """
        CLASSIC (no LLM) — returns the hint that historically led to the
        best outcome for this task type, for the BDI to reuse (warm-start).

        Used by the BDIPlannerAgent to close the learning loop:
          Verifier records hints -> Learner stores them ->
          BDI queries the best one for the next task of the same type.

        Selection: highest reward first, then highest payoff.
        Skips "no_hint" and anything in `exclude` (already tried).
        Returns "" if nothing usable is found.
        """
        self._load_from_disk()
        exclude_set = set(exclude or [])
        candidates  = []
        for s in self.get_strategies_for_task(task_type):
            hint = s.steps[0] if s.steps else ""
            if not hint or hint == "no_hint" or hint in exclude_set:
                continue
            if require_success and s.reward < 1.0:
                continue
            candidates.append((s.reward, s.payoff, hint))
        if not candidates:
            return ""
        # Sort by reward (ground truth) then payoff (quality)
        candidates.sort(key=lambda c: (c[0], c[1]), reverse=True)
        return candidates[0][2]

    def get_best_hint_ucb1(self, task_type: str,
                           exclude: Optional[List[str]] = None) -> str:
        """
        UCB1 variant of get_best_hint() (config.UCB1_ENABLED) — avoids
        greedy-argmax's failure mode where one lucky early attempt with
        the single highest payoff permanently dominates a plan that is
        actually more reliable on average.

        Arms are `plan_name`, not raw hint text: hints like Fallback's
        embed attempt count / best_u_v and are never byte-identical
        across attempts, so grouping by hint text would give every
        attempt its own arm of size 1. plan_name is stable and small.

        score(arm) = mean_payoff(arm) + sqrt(2*ln(N_total)/n(arm))

        Selection is two-level: UCB1 picks the arm (plan_name) among
        arms with >=1 success (same guard as get_best_hint: never
        warm-start with a plan that has never succeeded); within that
        arm, the existing greedy (reward, payoff) sort picks the actual
        hint text to return.
        """
        self._load_from_disk()
        exclude_set = set(exclude or [])
        records = [
            s for s in self.get_strategies_for_task(task_type)
            if s.plan_name and s.steps and s.steps[0]
            and s.steps[0] != "no_hint" and s.steps[0] not in exclude_set
        ]
        if not records:
            return ""

        by_arm: dict = {}
        for s in records:
            by_arm.setdefault(s.plan_name, []).append(s)

        arms_with_success = {
            name: recs for name, recs in by_arm.items()
            if any(r.reward >= 1.0 for r in recs)
        }
        if not arms_with_success:
            return ""

        n_total = len(records)
        best_arm, best_score = None, float("-inf")
        for name, recs in arms_with_success.items():
            n = len(recs)
            mean_payoff = sum(r.payoff for r in recs) / n
            score = mean_payoff + math.sqrt(2 * math.log(n_total) / n)
            if score > best_score:
                best_arm, best_score = name, score

        candidates = [(r.reward, r.payoff, r.steps[0]) for r in arms_with_success[best_arm]]
        candidates.sort(key=lambda c: (c[0], c[1]), reverse=True)
        return candidates[0][2]

    def get_learning_summary(self, task_type: str) -> str:
        strats = self.strategies.get(task_type, [])
        if not strats:
            return f"No strategy learned for {task_type}"
        payoffs = [s.payoff for s in strats]
        avg  = sum(payoffs) / len(payoffs)
        best = max(payoffs)
        n_ok = sum(1 for p in payoffs if p >= self.keep_threshold)
        return (f"{task_type} : {len(strats)} runs | "
                f"U_PE_moy={avg:.3f} | best={best:.3f} | "
                f"{n_ok}/{len(strats)} exploitables")

    # ── Persistence ───────────────────────────────────────────

    def _save_to_disk(self) -> None:
        os.makedirs(self._results_dir, exist_ok=True)
        with self._lock:
            data = {}
            for task_type, strats in self.strategies.items():
                data[task_type] = [
                    {"steps":      s.steps,
                     "payoff":     s.payoff,
                     "reward":     s.reward,
                     "task_type":  s.task_type,
                     "run_number": s.run_number,
                     "steps_used": s.steps_used,
                     "timestamp":  s.timestamp,
                     "plan_name":  s.plan_name}
                    for s in strats
                ]
            with open(self.strategies_file, "w", encoding="utf-8") as f:
                json.dump(data, f, indent=2, ensure_ascii=False)

    def _load_from_disk(self) -> None:
        if not os.path.exists(self.strategies_file):
            return
        try:
            with open(self.strategies_file, encoding="utf-8") as f:
                data = json.load(f)
            with self._lock:
                self.strategies = {}
                for task_type, strats in data.items():
                    self.strategies[task_type] = [
                        ActionStrategy(
                            steps      = s["steps"],
                            payoff     = s["payoff"],
                            reward     = s["reward"],
                            task_type  = s["task_type"],
                            run_number = s["run_number"],
                            steps_used = s["steps_used"],
                            timestamp  = s.get("timestamp", 0.0),
                            plan_name  = s.get("plan_name", ""),
                        )
                        for s in strats
                    ]
            total = sum(len(v) for v in self.strategies.values())
            if total:
                print(f"  [Learner] {total} strategies loaded from disk")
        except Exception as e:
            print(f"  [Learner] Load failed : {e}")
